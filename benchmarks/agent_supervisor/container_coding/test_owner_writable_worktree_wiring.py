"""Execute generated owner provisioning statements before worker preparation.

The helper is authored here to isolate deployed ordering and deadline flow.
Real descriptor transitions and native continuation are checked separately.
"""
import math
from pathlib import Path
import pathlib
import sys
import time

import pytest

from benchmarks.agent_supervisor.container_coding.container_worker_deployment import OWNER_ENTRY
from ipfs_accelerate_py.agent_supervisor.runtime import owner_provider_deadline as deadlines
from ipfs_accelerate_py.agent_supervisor.runtime import owner_writable_worktree as provisioning


def setup_code():
    start = OWNER_ENTRY.index("if cwd.resolve()!=cwd")
    stop = OWNER_ENTRY.index("owner_prompt_bytes=None")
    return compile(OWNER_ENTRY[start:stop], "<installed-owner-workspace-setup>", "exec")


def namespace(tmp_path, monkeypatch, *, inherited, timeout=90):
    root = tmp_path / "deployment"
    worktree_root = tmp_path / "worktrees"
    cwd = worktree_root / "candidate"
    cwd.mkdir(parents=True)
    started = time.monotonic()
    monkeypatch.setattr(sys, "argv", [deadlines.OWNER_WRAPPER, "--timeout", str(timeout)])
    return dict(root=root, cwd=cwd, boundary={"allowed_worktree_roots": [str(worktree_root)]},
        sys=sys, math=math, time=time, pathlib=pathlib,
        owner_candidate_round_started=started, owner_provider_deadline_ns=inherited)


@pytest.mark.parametrize("inherited_seconds,timeout", [(None, 90), (30, 90), (30, 1)])
def test_exact_generated_setup_passes_remaining_original_budget_before_worker_arguments(
        tmp_path, monkeypatch, inherited_seconds, timeout):
    inherited = None if inherited_seconds is None else time.monotonic_ns() + inherited_seconds * 1_000_000_000
    state = namespace(tmp_path, monkeypatch, inherited=inherited, timeout=timeout)
    calls = []
    receipt = {"authored_provisioning_receipt": True}

    def provision(**kwargs):
        assert "worker_arguments" not in state
        calls.append(kwargs)
        return receipt

    monkeypatch.setattr(provisioning, "provision_owner_writable_worktree", provision)
    exec(setup_code(), state)
    local_numerator, local_denominator = (state["owner_candidate_round_started"] + timeout).as_integer_ratio()
    local_cap = local_numerator * 1_000_000_000 // local_denominator
    expected = local_cap if inherited is None else min(local_cap, inherited)
    assert calls == [dict(boundary=state["root"] / "container-boundary.json",
        workspace=state["cwd"], absolute_deadline_ns=expected)]
    assert state["owner_workspace_provisioning"] is receipt
    assert state["worker_arguments"] == ["--timeout", str(timeout)]


@pytest.mark.parametrize("error_type", [ValueError, TimeoutError])
def test_generated_setup_refusal_does_not_begin_worker_arguments_or_first_census(
        tmp_path, monkeypatch, error_type):
    inherited = time.monotonic_ns() + 30_000_000_000
    state = namespace(tmp_path, monkeypatch, inherited=inherited)
    calls = []
    original = error_type("authored workspace refusal")

    def refuse(**kwargs):
        calls.append(kwargs)
        raise original

    monkeypatch.setattr(provisioning, "provision_owner_writable_worktree", refuse)
    with pytest.raises(error_type) as caught:
        exec(setup_code(), state)
    assert caught.value is original and len(calls) == 1
    assert "worker_arguments" not in state
    assert "owner_workspace_provisioning" not in state
    assert "owner_worker_attempt" not in state
    assert "worker_source_broker" not in state


@pytest.mark.parametrize("argument", ["--owner-worker-attempt-id", "--owner-worker-attempt-id=fake"])
def test_reserved_first_attempt_flag_is_refused_before_any_workspace_mutation(
        tmp_path, monkeypatch, argument):
    state = namespace(tmp_path, monkeypatch, inherited=None)
    monkeypatch.setattr(sys, "argv", [deadlines.OWNER_WRAPPER, argument, "fake"])
    monkeypatch.setattr(deadlines, "consume_owner_provider_deadline_handoff", lambda **_kwargs: None)
    calls = []
    monkeypatch.setattr(provisioning, "provision_owner_writable_worktree", lambda **kwargs: calls.append(kwargs))
    start = OWNER_ENTRY.index("from ipfs_accelerate_py.agent_supervisor.runtime.owner_provider_deadline import")
    stop = OWNER_ENTRY.index("owner_prompt_bytes=None")
    with pytest.raises(SystemExit, match="worker attempt identity is generated by the owner"):
        exec(compile(OWNER_ENTRY[start:stop], "<installed-owner-reserved-first-attempt>", "exec"), state)
    assert calls == [] and "owner_workspace_provisioning" not in state
