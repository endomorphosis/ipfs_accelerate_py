    workspace = worktrees / "workspace-ephemeral"
    worktrees.mkdir()
    shared = tmp_path / rel
    shared.parent.mkdir(parents=True)
    before = b"shared-authoritative\n"
    shared.write_bytes(before)
    todo = tmp_path / "tasks.todo.md"
