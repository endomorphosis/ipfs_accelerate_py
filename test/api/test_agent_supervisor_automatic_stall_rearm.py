def test_process_generation_reuses_live_pid_and_rotates_after_owner_change(
    tmp_path: Path,
    monkeypatch,
) -> None:
    import os

    receipt = tmp_path / "automatic_stall_rearm.json"
    pid = os.getpid()
    first, _payload = load_or_create_process_generation(receipt, pid=pid)
    second, again = load_or_create_process_generation(receipt, pid=pid)
    assert first == second
    assert again["process_generation"] == first

    def _dead_pid(*_args, **_kwargs):
        raise OSError("dead")

    monkeypatch.setattr(
        "ipfs_accelerate_py.agent_supervisor.todo_daemon.automatic_stall_rearm.os.kill",
        _dead_pid,
    )
    third, rotated = load_or_create_process_generation(receipt, pid=pid)
    assert third != first
    assert rotated["process_generation"] == third


def test_daemon_rearms_attempt_cap_and_identical_failure_once_per_process(
    tmp_path: Path,
    monkeypatch,
) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    todo_path = repo / "tasks.todo.md"
    _board(todo_path)
    daemon = _daemon(repo, todo_path, monkeypatch)
    source, repair = parse_task_file(todo_path, TASK_PREFIX)
    daemon._register_task_identities((source, repair))
    source_identity = daemon._identity_for_task(source)
    repair_identity = daemon._identity_for_task(repair)

    state = PortalTaskState(
        task_identities={
            source.task_id: source_identity.to_dict(),
            repair.task_id: repair_identity.to_dict(),
        },
        implementation_attempts={source.task_id: 2, repair.task_id: 2},
        implementation_attempts_by_cid={
            source_identity.canonical_task_cid: 2,
            repair_identity.canonical_task_cid: 2,
        },
    )
    state.save(daemon.state_path)
    daemon.task_queue.register_task(source_identity).record_failure("validation")
    daemon.task_queue.register_task(repair_identity).record_failure("validation")
    daemon.task_queue.save()
    diagnostic = daemon.implementation_log_dir / "test-001-diagnostic-state.json"
    diagnostic.parent.mkdir(parents=True, exist_ok=True)
    diagnostic.write_text(
        json.dumps({"repeat_count": 8, "not_before": 9_999_999_999.0}),
        encoding="utf-8",
    )

    first = daemon._rearm_process_generation_stalls(
        state,
        (source, repair),
        {source.task_id: "ready", repair.task_id: "ready"},
    )
    persisted = PortalTaskState.load(daemon.state_path)

    assert {item["task_id"] for item in first} == {source.task_id, repair.task_id}
    assert source.task_id not in persisted.implementation_attempts
    assert repair.task_id not in persisted.implementation_attempts
    assert json.loads(diagnostic.read_text(encoding="utf-8"))["repeat_count"] == 1
    assert daemon.task_queue.is_cooled_down(source_identity.canonical_task_cid) is False

    persisted.implementation_attempts[source.task_id] = 2
    persisted.implementation_attempts_by_cid[source_identity.canonical_task_cid] = 2
    persisted.save(daemon.state_path)
    second = daemon._rearm_process_generation_stalls(
        persisted,
        (source, repair),
        {source.task_id: "ready", repair.task_id: "ready"},
    )
    assert {item["task_id"] for item in second} == {source.task_id}
    assert all(item.get("already_granted") for item in second)
    assert persisted.implementation_attempts[source.task_id] == 2
    selectable, limited = daemon._partition_tasks_at_attempt_limit(
        (source, repair),
        {source.task_id: "ready", repair.task_id: "ready"},
        persisted,
        exempt_task_ids=tuple(item["task_id"] for item in second),
    )
    assert {task.task_id for task in selectable} == {source.task_id, repair.task_id}
    assert limited == []


def test_retry_budget_error_falls_back_to_fresh_compile() -> None:
    class BudgetError(Exception):
        pass

    mode, value = recover_retry_compile(
        compile_retry=lambda: (_ for _ in ()).throw(BudgetError("too big")),
        compile_fresh=lambda: "fresh-context",
        budget_errors=(BudgetError,),
    )
    assert mode == "fresh"
    assert value == "fresh-context"
    mode, value = recover_retry_compile(
        compile_retry=lambda: "retry-context",
        compile_fresh=lambda: "fresh-context",
        budget_errors=(BudgetError,),
    )
    assert mode == "retry"
    assert value == "retry-context"


def test_safe_run_once_keeps_daemon_alive_after_crash() -> None:
    def boom():
        raise RuntimeError("reconstructed full context exceeds the effective input budget")

    result = safe_run_once(boom)
    assert result["crashed"] is True
    assert result["error_type"] == "RuntimeError"
    assert result["selection_idle_reason"] == "daemon_pass_crashed_recovered"
    assert safe_run_once(lambda: {"ok": True}) == {"ok": True}


def test_fingerprint_is_unique_per_process_generation() -> None:
    first = rearm_fingerprint(
        process_generation_id="sha256:aaa",
        canonical_task_cid="cid-1",
        stall_class=STALL_MAX_TASK_ATTEMPTS,
    )
    second = rearm_fingerprint(
        process_generation_id="sha256:bbb",
        canonical_task_cid="cid-1",
        stall_class=STALL_MAX_TASK_ATTEMPTS,
    )
    assert first != second
    assert receipts_already_granted(
        {"cid-1": [first]},
        canonical_task_cid="cid-1",
        fingerprints=[first],
    )
    assert not receipts_already_granted(
        {"cid-1": [first]},
        canonical_task_cid="cid-1",
        fingerprints=[second],
    )


def test_claim_rearm_receipt_is_once_per_process_generation(tmp_path: Path) -> None:
    import os

    receipt = tmp_path / "automatic_stall_rearm.json"
