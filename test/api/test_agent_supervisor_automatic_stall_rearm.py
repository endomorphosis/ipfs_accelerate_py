TASK_PREFIX = "## TEST-"


def _board(path: Path) -> None:
    path.write_text(
        """# Tasks

## TEST-001 Seal the remaining ready contract

- Status: todo
- Completion: auto
- Priority: P0
- Track: contracts
- Outputs: src/contract.py
- Validation: python -m pytest -q
- Acceptance: Implement the remaining ready contract.

## TEST-002 Resolve validation retry-budget failure for TEST-001

- Status: todo
- Completion: manual
- Priority: P1
- Track: ops
- Outputs: src/contract.py
- Validation: python -m pytest -q
- Generated by: ipfs_accelerate_py.agent_supervisor.retry-budget-repair@1
- Retry repair source: TEST-001
- Retry failure kind: validation
- Acceptance: Use the durable failure evidence, then release TEST-001 from strategy blocked_tasks.
""",
        encoding="utf-8",
    )


def _daemon(repo: Path, todo_path: Path, monkeypatch) -> PortalImplementationDaemon:
    from ipfs_accelerate_py.agent_supervisor.merge.worktree_lifecycle import (
        WorktreeLifecycleStore,
    )

    monkeypatch.setattr(
        WorktreeLifecycleStore,
        "reclaim_dead_owners_for_controlled_restart",
        lambda self, *args, **kwargs: None,
        raising=False,
    )
    state_dir = repo / "state"
    return PortalImplementationDaemon(
        todo_path=todo_path,
        state_path=state_dir / "task_state.json",
        strategy_path=state_dir / "strategy.json",
        events_path=state_dir / "events.jsonl",
        repo_root=repo,
        task_header_prefix=TASK_PREFIX,
        max_task_attempts=2,
        implementation_max_repair_rounds=3,
        worktree_pool_enabled=False,
    )


