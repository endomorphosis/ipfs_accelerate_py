"""Operational-appendix checks for the logic-family parser board validator."""

from __future__ import annotations

import json
from dataclasses import replace
from pathlib import Path

from ipfs_accelerate_py.agent_supervisor.todo_daemon.implementation_daemon import (
    RECONCILIATION_GUARDRAIL_SCHEMA,
    RECONCILIATION_RESOLUTION_SCHEMA,
    PortalTask,
)

from scripts import validate_ipfs_datasets_logic_family_parser_board as validator


def _guardrail_task(
    repo_root: Path,
    *,
    task_id: str = "LFP-048",
    kind: str = "preflight_merge_conflict",
    fingerprint: str = "a" * 40,
    status: str = "blocked",
) -> tuple[PortalTask, Path, Path]:
    todo_path = (
        repo_root
        / "docs"
        / "architecture"
        / "ipfs_datasets_logic_family_parser.todo.md"
    )
    discovery_root = (
        repo_root
        / "data"
        / "agent_supervisor"
        / "ipfs_datasets_logic_family_parser"
        / "state"
        / "discovery"
    )
    discovery_path = discovery_root / (
        f"2026-08-09-{task_id.lower()}-reconciliation-{fingerprint[:12]}.md"
    )
    discovery_path.parent.mkdir(parents=True, exist_ok=True)
    discovery_path.write_text("# Reconciliation evidence\n", encoding="utf-8")
    reason = kind
    if kind == "main_checkout_dirty":
        title = "Resolve dirty main checkout blocking 2 worktree merges"
        dedupe_key = "reconciliation_guardrail:main_checkout_dirty"
    else:
        title = "Resolve 2 preflight-conflicting backlogged worktree merges"
        dedupe_key = "reconciliation_guardrail:preflight_merge_conflict"
    discovery_text = str(discovery_path)
    task = PortalTask(
        task_id=task_id,
        title=title,
        status=status,
        completion="manual",
        priority="P1",
        track="ops",
        outputs=[
            "data/agent_supervisor/ipfs_datasets_logic_family_parser/state/discovery",
            "docs/architecture/ipfs_datasets_logic_family_parser.todo.md",
        ],
        validation=[f"test -f {discovery_text}"],
        acceptance=(
            "Reconciliation guardrail filed this because 2 branch or worktree "
            f"cleanup candidates are blocked by {reason}. Use evidence in "
            f"{discovery_text}."
        ),
        metadata={
            "generated by": RECONCILIATION_GUARDRAIL_SCHEMA,
            "reconciliation kind": kind,
            "reconciliation reason": reason,
            "reconciliation fingerprint": fingerprint,
            "reconciliation discovery": discovery_text,
            "canonical board task": "false",
            "fingerprint": fingerprint,
            "dedupe key": dedupe_key,
            "is schedulable": "false",
            "review only": "true",
            "blocked reason": "operator_reconciliation_required",
            "goal id": "LFP-G000",
            "bundle": "logic-family-parser/control",
            "parallel lane": "lfp-control",
            "resource class": "cpu-small",
        },
        board_namespace="ipfs-datasets-logic-family-parser-v1",
    )
    return task, todo_path, discovery_path


def _validate(task: PortalTask, repo_root: Path, todo_path: Path) -> list[str]:
    errors: list[str] = []
    validator._validate_reconciliation_guardrail_tasks(
        [task],
        repo_root=repo_root,
        todo_path=todo_path,
        errors=errors,
    )
    return errors


def test_exact_reconciliation_provenance_is_partitioned_and_validated(
    tmp_path: Path,
) -> None:
    task, todo_path, _discovery_path = _guardrail_task(tmp_path)

    assert validator._is_reconciliation_guardrail_task(task) is True
    assert _validate(task, tmp_path, todo_path) == []

    wrong_producer = replace(
        task,
        metadata={**task.metadata, "generated by": "untrusted-producer@1"},
    )
    canonical_claim = replace(
        task,
        metadata={**task.metadata, "canonical board task": "true"},
    )
    assert validator._is_reconciliation_guardrail_task(wrong_producer) is False
    assert validator._is_reconciliation_guardrail_task(canonical_claim) is False
    assert validator._looks_like_reconciliation_guardrail_task(wrong_producer)
    assert validator._looks_like_reconciliation_guardrail_task(canonical_claim)

    marker_only = replace(
        task,
        metadata={
            key: value
            for key, value in task.metadata.items()
            if key not in {"generated by", "canonical board task"}
        },
    )
    assert validator._is_reconciliation_guardrail_task(marker_only) is False
    assert validator._looks_like_reconciliation_guardrail_task(marker_only)


def test_blocked_reconciliation_requires_bounded_regular_evidence(
    tmp_path: Path,
) -> None:
    task, todo_path, discovery_path = _guardrail_task(tmp_path)
    discovery_path.unlink()

    assert "LFP-048 reconciliation evidence is not a regular file" in _validate(
        task,
        tmp_path,
        todo_path,
    )


def test_reconciliation_appendix_rejects_scope_and_identity_forgery(
    tmp_path: Path,
) -> None:
    task, todo_path, discovery_path = _guardrail_task(tmp_path)
    forged = replace(
        task,
        outputs=[
            task.outputs[0],
            "docs/architecture/another.todo.md",
        ],
        validation=[f"test -f {discovery_path.parent.parent / discovery_path.name}"],
        metadata={
            **task.metadata,
            "goal id": "LFP-G010",
            "fingerprint": "b" * 40,
        },
    )

    errors = _validate(forged, tmp_path, todo_path)

    assert "LFP-048 reconciliation fingerprint mismatch" in errors
    assert "LFP-048 reconciliation root profile mismatch: goal id" in errors
    assert "LFP-048 reconciliation output scope mismatch" in errors
    assert "LFP-048 reconciliation validation escapes its output" in errors


def test_completed_reconciliation_requires_content_addressed_resolution_receipt(
    tmp_path: Path,
) -> None:
    task, todo_path, discovery_path = _guardrail_task(
        tmp_path,
        status="completed",
    )
    receipt: dict[str, object] = {
        "schema": RECONCILIATION_RESOLUTION_SCHEMA,
        "task_id": task.task_id,
        "reconciliation_fingerprint": task.metadata[
            "reconciliation fingerprint"
        ],
        "kind": task.metadata["reconciliation kind"],
        "reason": task.metadata["reconciliation reason"],
        "resolved": True,
        "resolved_at": "2026-08-09T04:00:00+00:00",
        "resolution_method": "verified_reconciliation",
        "postconditions": {
            "candidate_count_before": 2,
            "candidate_count_after": 0,
            "active_blocker_present_after": False,
            "dirty_worktree_group_count_after": 0,
            "cleanup_skip_count_after": 0,
        },
        "evidence": {"result": "clean rescan"},
    }
    receipt["receipt_digest"] = validator._resolution_receipt_digest(receipt)
    discovery_path.parent.mkdir(parents=True, exist_ok=True)
    discovery_path.write_text(
        "# Reconciliation evidence\n\n## Resolution Receipt\n\n```json\n"
        + json.dumps(receipt, indent=2, sort_keys=True)
        + "\n```\n",
        encoding="utf-8",
    )
    completed = replace(
        task,
        metadata={
            **task.metadata,
            "resolution receipt digest": str(receipt["receipt_digest"]),
        },
    )

    assert _validate(completed, tmp_path, todo_path) == []

    forged = replace(
        completed,
        metadata={
            **completed.metadata,
            "resolution receipt digest": "sha256:" + ("0" * 64),
        },
    )
    assert "LFP-048 resolution receipt anchor mismatch" in _validate(
        forged,
        tmp_path,
        todo_path,
    )


