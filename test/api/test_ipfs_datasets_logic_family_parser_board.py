def test_reconciliation_appendix_count_is_bounded(
    tmp_path: Path,
    monkeypatch,
) -> None:
    first, todo_path, _first_discovery = _guardrail_task(tmp_path)
    second, _todo_path, _second_discovery = _guardrail_task(
        tmp_path,
        task_id="LFP-049",
        kind="main_checkout_dirty",
        fingerprint="b" * 40,
    )
    monkeypatch.setattr(validator, "MAX_OPERATIONAL_RECONCILIATION_TASKS", 1)
    errors: list[str] = []

    validator._validate_reconciliation_guardrail_tasks(
        [first, second],
        repo_root=tmp_path,
        todo_path=todo_path,
        errors=errors,
    )

    assert "operational reconciliation appendix exceeds its finite bound" in errors
