def safe_diagnostics(error):
    chain, frames, seen = [], [], []
    current = error
    while isinstance(current, BaseException) and len(chain) < 8 and not any(current is old for old in seen):
        seen.append(current)
        name = type(current).__name__
        item = {'type': name if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]{0,79}', name) else 'unclassified_exception'}
        args = current.args
        if type(args) is tuple and len(args) == 1 and type(args[0]) is str and args[0] in _CODES:
            item['reason_code'] = args[0]
        chain.append(item)
        cursor, rows, count = current.__traceback__, [], 0
        while cursor is not None and count < 128:
            code = cursor.tb_frame.f_code
            path = code.co_filename
            if type(path) is str and 0 < len(path) <= 512 and os.path.isabs(path) and not any(c in path for c in '\x00\r\n\t'):
                rows.append({'source_path': path, 'line': cursor.tb_lineno})
            cursor = cursor.tb_next; count += 1
        remaining = 16 - len(frames)
        if remaining > 0:
            frames.extend(rows[-remaining:])
        current = current.__cause__ if current.__cause__ is not None else current.__context__
    return {'cause_chain': chain, 'source_frames': frames, 'locals_or_keys_included': False}
