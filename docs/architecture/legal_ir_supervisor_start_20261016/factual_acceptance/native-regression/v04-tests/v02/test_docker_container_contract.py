def test_explicit_engineering_container_metadata_contract_is_accepted():
    actual, expected = normative_contract()
    before = copy.deepcopy((actual, expected))
    state = backend.verify_container(actual, expected, running=False)
    assert state == {"Running": False, "Status": "created", "Pid": 0, "OOMKilled": False}
    assert (actual, expected) == before


@pytest.mark.parametrize("fault", [
    "wrong_image", "network_access", "writable_root", "privileged", "root_uid",
    "different_command_or_environment", "extra_writable_mount", "missing_readonly_source",
    "docker_socket", "host_device", "resource_bounds_broadened", "unexpected_running_state",
    "unexpected_tmpfs", "widened_ulimits", "missing_ulimit", "host_cgroup_namespace",
])
def test_unsafe_container_metadata_is_refused_without_runtime_effects(fault):
    actual, expected = normative_contract()
    frozen_expected = copy.deepcopy(expected)
    host, config = actual["HostConfig"], actual["Config"]
    if fault in {"different_command_or_environment", "resource_bounds_broadened", "widened_ulimits", "host_device"}:
        # Independent mutations each reach the real pure verifier. These loops
        # avoid inflating JUnit cases without combining unsafe fields in one row.
        alternatives = ({"Cmd": ["-i", "/bin/sh"],
                         "Env": config["Env"] + ["AUTH_TOKEN=authored-nonsecret-canary"]}
                        if fault == "different_command_or_environment" else
                        {"NanoCpus": 2000000000, "Memory": 536870912, "PidsLimit": 256}
                        if fault == "resource_bounds_broadened" else
                        {"Devices": [{"PathOnHost": "/dev/authored-device", "PathInContainer": "/dev/authored-device", "CgroupPermissions": "rwm"}],
                         "GroupAdd": ["0"], "DeviceCgroupRules": ["a *:* rwm"]}
                        if fault == "host_device" else
                        {name: value for name, value in (("cpu", 240), ("fsize", 4194304), ("nofile", 128))})
        for key, value in alternatives.items():
            mutated = copy.deepcopy(actual)
            if fault == "different_command_or_environment":
                mutated["Config"][key] = value
            elif fault in {"resource_bounds_broadened", "host_device"}:
                mutated["HostConfig"][key] = value
            else:
                limit = next(item for item in mutated["HostConfig"]["Ulimits"] if item["Name"] == key)
                limit.update(Soft=value, Hard=value)
            with pytest.raises(backend.acceptance.AcceptanceRefusal):
                backend.verify_container(mutated, expected, running=False)
        assert expected == frozen_expected
        return
    if fault == "wrong_image":
        actual["Image"] = "sha256:" + "0" * 64
    elif fault == "network_access":
        host["NetworkMode"] = "bridge"
    elif fault == "writable_root":
        host["ReadonlyRootfs"] = False
    elif fault == "privileged":
        host["Privileged"] = True
    elif fault == "root_uid":
        config["User"] = "0:0"
    elif fault == "extra_writable_mount":
        # Preserve mount count while broadening a previously read-only checker.
        next(item for item in actual["Mounts"] if item["Destination"] == "/opt/legal-ir/factual_candidate.py")["RW"] = True
    elif fault == "missing_readonly_source":
        actual["Mounts"] = [item for item in actual["Mounts"] if item["Destination"] != "/opt/legal-ir/factual_candidate.py"]
    elif fault == "docker_socket":
        actual["Mounts"].append({"Type": "bind", "Source": "/var/run/docker.sock",
            "Destination": "/var/run/docker.sock", "RW": True, "Propagation": "rprivate"})
    elif fault == "unexpected_tmpfs":
        host["Tmpfs"] = {"/outside-attempt": "rw,size=1048576"}
    elif fault == "host_cgroup_namespace":
        host["CgroupnsMode"] = "host"
    elif fault == "missing_ulimit":
        host["Ulimits"] = [item for item in host["Ulimits"] if item["Name"] != "nofile"]
    else:
        actual["State"].update(Running=True, Status="running", Pid=1234)
    with pytest.raises(backend.acceptance.AcceptanceRefusal):
        backend.verify_container(actual, expected, running=False)
    assert expected == frozen_expected
