"""Exact canonical terminal support roles, shared by numerical and Doctor consumers.

The caller verifies manifest provenance. This checker replays generated bytes,
all source names and the independent public task contract; it grants no authority.
"""
from __future__ import annotations
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import stat
from ..proof.formal_verification_contracts import content_identity
from . import local_planning_admission as local
from .terminal_task_profile import (INSTRUCTION, PROFILE, SMOKE, task_profile_bytes,
    task_profile_smoke, task_profile_spec, task_profile_worker_inputs,
    validate_task_profile, normalized_instruction)

class TerminalSourcePartitionError(ValueError):
    """Signed harness support cannot be independently reproduced."""

def _unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise TerminalSourcePartitionError("duplicate task profile key")
        result[key] = value
    return result


def _read(root: Path, name: str, sources: dict, limit: int) -> bytes:
    path = root / name
    if (path.is_symlink() or path.resolve(strict=True) != path or not path.is_file()
            or path.stat().st_size > limit):
        raise TerminalSourcePartitionError("bounded regular signed support file required")
    with os.fdopen(os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), "rb") as stream:
        before = os.fstat(stream.fileno())
        if not stat.S_ISREG(before.st_mode) or before.st_nlink != 1 or before.st_size > limit:
            raise TerminalSourcePartitionError("bounded regular signed support file required")
        raw = stream.read(limit + 1)
        after = os.fstat(stream.fileno())
    identity = lambda value: (value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns, value.st_ctime_ns)
    if (identity(before) != identity(after) or identity(path.lstat()) != identity(before)
            or path.resolve(strict=True) != path):
        raise TerminalSourcePartitionError("harness support changed during verification")
    if len(raw) > limit or hashlib.sha256(raw).hexdigest() != sources[name]["sha256"]:
        raise TerminalSourcePartitionError("harness support differs from signed source")
    return raw


@dataclass(frozen=True)
class TerminalSourcePartition:
    profile_sha256: str
    program_paths: tuple[str, ...]
    support_hashes: tuple[tuple[str, str, str], ...]


def terminal_profile_partition(*, repository: Path, manifest: dict) -> TerminalSourcePartition | None:
    root = Path(repository).absolute()
    if root.resolve(strict=True) != root or str(root) != manifest["repository"]:
        raise TerminalSourcePartitionError("partition repository differs from manifest")
    sources = manifest["sources"]
    if PROFILE not in sources:
        return None
    if len(manifest["tasks"]) != 1:
        raise TerminalSourcePartitionError("partition requires the single signed public task")
    if not {INSTRUCTION, SMOKE} <= set(sources):
        raise TerminalSourcePartitionError("signed harness support is incomplete")
    raw = _read(root, PROFILE, sources, 65536)
    instruction = _read(root, INSTRUCTION, sources, 32768).decode("utf-8")
    if not instruction.strip() or normalized_instruction(instruction) != instruction:
        raise TerminalSourcePartitionError("canonical nonempty public instruction required")
    try:
        profile = validate_task_profile(json.loads(raw, object_pairs_hook=_unique_pairs), instruction=instruction)
    except (ValueError, TypeError) as error:
        raise TerminalSourcePartitionError("signed public task profile is invalid") from error
    if raw != task_profile_bytes(profile):
        raise TerminalSourcePartitionError("task profile is not the canonical producer output")
    if set(sources) != set(task_profile_worker_inputs(profile)):
        raise TerminalSourcePartitionError("partition omits or adds signed source inputs")
    expected_spec = task_profile_spec(profile, policy_cid=content_identity(local.LOCAL_POLICY))
    if "planning_inputs" in manifest:
        # Recompute selected evidence from the signed native planning inputs.
        _, evidence = local._verify_planning_inputs(manifest)
        if not evidence:
            raise TerminalSourcePartitionError("public planning profile requires selected evidence")
        expected_spec["acceptance"][0]["evidence_cids"] = [evidence[0].evidence_cid]
    if manifest["tasks"][0] != expected_spec:
        raise TerminalSourcePartitionError("profile differs from independently signed task effects or checks")
    expected_smoke = task_profile_smoke(profile).encode("utf-8")
    if _read(root, SMOKE, sources, len(expected_smoke)) != expected_smoke:
        raise TerminalSourcePartitionError("structural smoke differs from the fixed producer")
    return TerminalSourcePartition(
        profile_sha256=hashlib.sha256(raw).hexdigest(),
        program_paths=tuple(profile["input_paths"]),
        support_hashes=tuple((name, role, sources[name]["sha256"]) for name, role in (
            (INSTRUCTION, "instruction"), (PROFILE, "task_profile"), (SMOKE, "structural_smoke"))))
