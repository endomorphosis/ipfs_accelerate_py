"""DCR-047 deterministic code-generation roundtrip validation.

The module validates already-observed offline generator runs.  It does not
load or execute a generator, write generated files, open a network route, or
grant mutation authority.  A valid result is therefore still integration
pending until DCR-070 admission and DCR-072 isolated execution are current.
"""

from __future__ import annotations

import base64
import hashlib
import re
from collections.abc import Sequence
from dataclasses import dataclass
from enum import Enum
from typing import Any, Final

from ...autonomous_repair.capabilities import (
    CapabilityEvidenceReceipt,
    CapabilityStatus,
    NetworkMode,
    SolverReadiness,
)
from ...proof.formal_verification_contracts import content_identity
from .registry import OPERATOR_REGISTRY_SCHEMA, OperatorDescriptor, OperatorRegistry

CODEGEN_ROUNDTRIP_SCHEMA: Final[str] = (
    "ipfs_accelerate_py/agent-supervisor/dcr-047-codegen-roundtrip@1"
)
CODEGEN_RUN_SCHEMA: Final[str] = (
    "ipfs_accelerate_py/agent-supervisor/dcr-047-generator-run-observation@1"
)
CODEGEN_OUTPUT_SCHEMA: Final[str] = (
    "ipfs_accelerate_py/agent-supervisor/dcr-047-generated-output-observation@1"
)
CODEGEN_ACTIVATION_STATUS: Final[str] = "integration_pending_dcr070_dcr072"
_ARGV_TOKEN = re.compile(r"^-{0,2}[A-Za-z0-9][A-Za-z0-9_.@/=:,+-]{0,383}$")


class CodegenRoundtripDisposition(str, Enum):  # noqa: UP042 - Python 3.8
    INTEGRATION_PENDING = "integration_pending"
    ABSTAINED = "abstained"
    REJECTED = "rejected"


class CodegenRoundtripError(ValueError):
    """A supplied generator observation is not closed deterministic evidence."""


def _sha256(value: bytes, *, label: str = "sha256") -> str:
    return f"{label}:{hashlib.sha256(value).hexdigest()}"


def _text(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value or value != value.strip():
        raise CodegenRoundtripError(f"{field} must be non-empty exact text")
    if "synthetic" in value.lower() or "expected-only" in value.lower():
        raise CodegenRoundtripError(f"{field} may not be synthetic or expected-only")
    return value


def _path(value: Any, field: str) -> str:
    result = _text(value, field)
    if result.startswith("/") or ".." in result.split("/") or "\x00" in result:
        raise CodegenRoundtripError(f"{field} must be a bounded relative path")
    return result


def _argv(value: Any) -> tuple[str, ...]:
    if not isinstance(value, Sequence) or isinstance(value, (str, bytes)) or not value:
        raise CodegenRoundtripError("generator argv must be a non-empty sequence")
    result = tuple(value)
    if any(not isinstance(item, str) or not _ARGV_TOKEN.fullmatch(item) for item in result):
        raise CodegenRoundtripError("generator argv contains a dynamic or shell token")
    return result


@dataclass(frozen=True)
class GeneratedOutputObservation:
    """Exact prior/generated bytes and roundtrip semantic identity for one file."""

    owner_root: str
    relative_path: str
    authority_source_cid: str
    before_bytes: bytes
    before_digest: str
    generated_bytes: bytes
    generated_digest: str
    semantic_cid: str
    decoded_semantic_cid: str
    authority_class: str = "derived_from_reviewed_source"
    hand_owned: bool = False

    def __post_init__(self) -> None:
        object.__setattr__(self, "owner_root", _text(self.owner_root, "owner_root"))
        object.__setattr__(self, "relative_path", _path(self.relative_path, "relative_path"))
        object.__setattr__(
            self,
            "authority_source_cid",
            _text(self.authority_source_cid, "authority_source_cid"),
        )
        if not isinstance(self.before_bytes, bytes) or not isinstance(self.generated_bytes, bytes):
            raise CodegenRoundtripError("generated observations require exact bytes")
        if self.before_digest != _sha256(self.before_bytes):
            raise CodegenRoundtripError("before bytes digest is stale")
        if not self.generated_bytes or self.generated_digest != _sha256(self.generated_bytes):
            raise CodegenRoundtripError("generated bytes digest is stale or empty")
        _text(self.semantic_cid, "semantic_cid")
        _text(self.decoded_semantic_cid, "decoded_semantic_cid")
        if type(self.hand_owned) is not bool:
            raise CodegenRoundtripError("hand_owned must be boolean")

    @property
    def output_key(self) -> tuple[str, str]:
        return self.owner_root, self.relative_path

    @property
    def inverse_cid(self) -> str:
        return content_identity(
            {
                "owner_root": self.owner_root,
                "relative_path": self.relative_path,
                "restore_digest": self.before_digest,
                "restore_base64": base64.b64encode(self.before_bytes).decode("ascii"),
            }
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": CODEGEN_OUTPUT_SCHEMA,
            "owner_root": self.owner_root,
            "relative_path": self.relative_path,
            "authority_source_cid": self.authority_source_cid,
            "before_base64": base64.b64encode(self.before_bytes).decode("ascii"),
            "before_digest": self.before_digest,
            "generated_base64": base64.b64encode(self.generated_bytes).decode("ascii"),
            "generated_digest": self.generated_digest,
            "semantic_cid": self.semantic_cid,
            "decoded_semantic_cid": self.decoded_semantic_cid,
            "authority_class": self.authority_class,
            "hand_owned": self.hand_owned,
            "inverse_cid": self.inverse_cid,
        }


@dataclass(frozen=True)
class GeneratorRunObservation:
    """One detector-produced, offline generator-run transcript projection."""

    run_ordinal: int
    generator_id: str
    executable_digest: str
    generator_version: str
    argv: tuple[str, ...]
    authority_source_cid: str
    forest_cid: str
    transcript_digest: str
    outputs: tuple[GeneratedOutputObservation, ...]
    exit_code: int = 0
    observation_mode: str = "detector_observed_offline"
    model_call_count: int = 0
    provider_call_count: int = 0
    network_call_count: int = 0

    def __post_init__(self) -> None:
        if self.run_ordinal not in {1, 2}:
            raise CodegenRoundtripError("run ordinal must be one or two")
        for field in (
            "generator_id",
            "executable_digest",
            "generator_version",
            "authority_source_cid",
            "forest_cid",
            "transcript_digest",
        ):
            object.__setattr__(self, field, _text(getattr(self, field), field))
        if not self.executable_digest.startswith("executable:sha256:"):
            raise CodegenRoundtripError("generator executable digest is not canonical")
        if not self.transcript_digest.startswith("transcript:sha256:"):
            raise CodegenRoundtripError("generator transcript digest is not canonical")
        object.__setattr__(self, "argv", _argv(self.argv))
        outputs = tuple(self.outputs)
        if not outputs or any(not isinstance(item, GeneratedOutputObservation) for item in outputs):
            raise CodegenRoundtripError("generator run requires typed generated outputs")
        if len({item.output_key for item in outputs}) != len(outputs):
            raise CodegenRoundtripError("generator output paths must be unique")
        object.__setattr__(
            self, "outputs", tuple(sorted(outputs, key=lambda item: item.output_key))
        )
        if self.exit_code != 0 or self.observation_mode != "detector_observed_offline":
            raise CodegenRoundtripError(
                "generator observation must be a successful offline detector run"
            )
        for field in ("model_call_count", "provider_call_count", "network_call_count"):
            if type(getattr(self, field)) is not int or getattr(self, field) != 0:
                raise CodegenRoundtripError(f"{field} must be exactly zero")

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": CODEGEN_RUN_SCHEMA,
            "run_ordinal": self.run_ordinal,
            "generator_id": self.generator_id,
            "executable_digest": self.executable_digest,
            "generator_version": self.generator_version,
            "argv": list(self.argv),
            "authority_source_cid": self.authority_source_cid,
            "forest_cid": self.forest_cid,
            "transcript_digest": self.transcript_digest,
            "outputs": [item.to_dict() for item in self.outputs],
            "exit_code": self.exit_code,
            "observation_mode": self.observation_mode,
            "model_call_count": 0,
            "provider_call_count": 0,
            "network_call_count": 0,
        }

    @property
    def content_id(self) -> str:
        return content_identity(self.to_dict())


@dataclass(frozen=True)
class CodegenRoundtripRequest:
    descriptor: OperatorDescriptor
    registry: OperatorRegistry
    pinned_registry_cid: str
    toolchain: SolverReadiness
    tool_evidence: tuple[CapabilityEvidenceReceipt, ...]
    authority_source_cid: str
    forest_cid: str
    owner_root: str
    generated_paths: tuple[str, ...]
    first_run: GeneratorRunObservation
    second_run: GeneratorRunObservation


@dataclass(frozen=True)
class CodegenRoundtripResult:
    disposition: CodegenRoundtripDisposition
    reason_codes: tuple[str, ...]
    request_cid: str = ""
    run_cids: tuple[str, ...] = ()
    output_cids: tuple[str, ...] = ()
    inverse_cids: tuple[str, ...] = ()
    execution_authorized: bool = False
    completion_authorized: bool = False
    model_call_count: int = 0
    provider_call_count: int = 0
    network_call_count: int = 0

    def to_dict(self) -> dict[str, Any]:
        body = {
            "schema": CODEGEN_ROUNDTRIP_SCHEMA,
            "authoritative": False,
            "activation_status": CODEGEN_ACTIVATION_STATUS,
            "disposition": self.disposition.value,
            "reason_codes": list(self.reason_codes),
            "request_cid": self.request_cid,
            "run_cids": list(self.run_cids),
            "output_cids": list(self.output_cids),
            "inverse_cids": list(self.inverse_cids),
            "execution_authorized": False,
            "completion_authorized": False,
            "model_call_count": 0,
            "provider_call_count": 0,
            "network_call_count": 0,
        }
        return {**body, "roundtrip_cid": content_identity(body)}


def _validate_registry(request: CodegenRoundtripRequest) -> None:
    if not isinstance(request.descriptor, OperatorDescriptor) or not isinstance(
        request.registry, OperatorRegistry
    ):
        raise CodegenRoundtripError("typed DCR-040 registry and descriptor are required")
    report = request.registry.report()
    body = dict(report)
    registry_cid = body.pop("registry_cid", "")
    if (
        report.get("schema") != OPERATOR_REGISTRY_SCHEMA
        or registry_cid != content_identity(body)
        or registry_cid != request.pinned_registry_cid
        or report.get("reviewed_manifest", {}).get(request.descriptor.operator_id)
        != request.descriptor.descriptor_id
        or request.descriptor not in request.registry.enumerate()
    ):
        raise CodegenRoundtripError("reviewed DCR-040 descriptor or registry pin is stale")


def _validate_tool(request: CodegenRoundtripRequest) -> None:
    tool = request.toolchain
    if (
        not isinstance(tool, SolverReadiness)
        or tool.status is not CapabilityStatus.AVAILABLE
        or not tool.available
        or tool.network_mode is not NetworkMode.OFFLINE
        or tool.expected_version != tool.version
        or not tool.executable_digest.startswith("executable:sha256:")
        or not tool.self_test_passed
        or not tool.reconstructed
        or tool.reason_codes
    ):
        raise CodegenRoundtripError("DCR-004 generator toolchain is not available offline")
    evidence = tuple(request.tool_evidence)
    if len(evidence) != 2 or any(
        not isinstance(item, CapabilityEvidenceReceipt) for item in evidence
    ):
        raise CodegenRoundtripError(
            "exact DCR-004 tool self-test and reconstruction evidence required"
        )
    by_kind = {item.evidence_kind: item for item in evidence}
    if set(by_kind) != {"self_test", "reconstruction"}:
        raise CodegenRoundtripError("tool evidence kinds must be exact and unique")
    expected_ids = {
        "self_test": tool.self_test_id,
        "reconstruction": tool.reconstruction_id,
    }
    for kind, item in by_kind.items():
        if not item.verifies(
            evidence_id=expected_ids[kind],
            evidence_kind=kind,
            subject_id=tool.tool_id,
            subject_digest=tool.executable_digest,
            subject_version=tool.version,
        ):
            raise CodegenRoundtripError("generator tool evidence is stale or unverified")


def _request_identity(request: CodegenRoundtripRequest) -> str:
    return content_identity(
        {
            "descriptor_id": request.descriptor.descriptor_id,
            "registry_cid": request.pinned_registry_cid,
            "toolchain_receipt_id": request.toolchain.receipt_id,
            "tool_evidence_ids": sorted(item.receipt_id for item in request.tool_evidence),
            "authority_source_cid": request.authority_source_cid,
            "forest_cid": request.forest_cid,
            "owner_root": request.owner_root,
            "generated_paths": list(request.generated_paths),
            "run_cids": [request.first_run.content_id, request.second_run.content_id],
        }
    )


def validate_codegen_roundtrip(request: Any) -> CodegenRoundtripResult:
    """Validate two exact generation observations without executing either run."""

    if not isinstance(request, CodegenRoundtripRequest):
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.REJECTED,
            ("typed_codegen_roundtrip_request_required",),
        )
    try:
        _validate_registry(request)
        _validate_tool(request)
        authority_source_cid = _text(request.authority_source_cid, "authority_source_cid")
        forest_cid = _text(request.forest_cid, "forest_cid")
        owner_root = _text(request.owner_root, "owner_root")
        generated_paths = tuple(
            sorted(_path(item, "generated_path") for item in request.generated_paths)
        )
        if not generated_paths or len(set(generated_paths)) != len(generated_paths):
            raise CodegenRoundtripError("generated path set must be non-empty and unique")
    except (CodegenRoundtripError, TypeError) as exc:
        return CodegenRoundtripResult(CodegenRoundtripDisposition.REJECTED, (str(exc),))

    first, second = request.first_run, request.second_run
    expected_binding = (
        request.toolchain.tool_id,
        request.toolchain.executable_digest,
        request.toolchain.version,
        authority_source_cid,
        forest_cid,
    )
    for run in (first, second):
        if (
            not isinstance(run, GeneratorRunObservation)
            or (
                run.generator_id,
                run.executable_digest,
                run.generator_version,
                run.authority_source_cid,
                run.forest_cid,
            )
            != expected_binding
        ):
            return CodegenRoundtripResult(
                CodegenRoundtripDisposition.REJECTED,
                ("generator_run_binding_is_stale",),
            )
    if first.run_ordinal != 1 or second.run_ordinal != 2 or first.argv != second.argv:
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.REJECTED,
            ("ordered_repeat_run_or_argv_binding_invalid",),
        )
    first_outputs = {item.output_key: item for item in first.outputs}
    second_outputs = {item.output_key: item for item in second.outputs}
    expected_keys = {(owner_root, path) for path in generated_paths}
    if set(first_outputs) != expected_keys or set(second_outputs) != expected_keys:
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.REJECTED,
            ("generated_output_set_or_owner_is_unexpected",),
        )
    if any(path not in request.descriptor.write_scope for path in generated_paths) or (
        request.descriptor.owner_root != owner_root
    ):
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.REJECTED,
            ("generated_output_is_outside_reviewed_write_scope",),
        )
    if any(
        item.authority_source_cid != authority_source_cid
        or item.authority_class != "derived_from_reviewed_source"
        or item.hand_owned
        or item.semantic_cid != item.decoded_semantic_cid
        for item in (*first.outputs, *second.outputs)
    ):
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.REJECTED,
            ("authority_source_or_semantic_roundtrip_is_invalid",),
        )
    if any(first_outputs[key].to_dict() != second_outputs[key].to_dict() for key in expected_keys):
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.ABSTAINED,
            ("repeat_generation_is_not_byte_identical",),
            run_cids=(first.content_id, second.content_id),
        )
    if not any(item.before_bytes != item.generated_bytes for item in first.outputs):
        return CodegenRoundtripResult(
            CodegenRoundtripDisposition.ABSTAINED,
            ("generation_has_no_source_change",),
            run_cids=(first.content_id, second.content_id),
        )
    output_cids = tuple(content_identity(item.to_dict()) for item in first.outputs)
    return CodegenRoundtripResult(
        CodegenRoundtripDisposition.INTEGRATION_PENDING,
        (CODEGEN_ACTIVATION_STATUS,),
        request_cid=_request_identity(request),
        run_cids=(first.content_id, second.content_id),
        output_cids=output_cids,
        inverse_cids=tuple(item.inverse_cid for item in first.outputs),
    )


