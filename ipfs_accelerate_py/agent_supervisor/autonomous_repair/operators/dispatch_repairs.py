"""DCR-043 static dispatch repair previews.

This module is deliberately only a parser and byte-patch constructor.  It does
not load a handler, query a capability provider, call an MCP endpoint, or write
the generated bytes.  A route label is not proof of purity, so all identities
used here are closed evidence supplied by the caller and checked against the
current source bytes.
"""

from __future__ import annotations

import ast
import base64
import difflib
import hashlib
from collections.abc import Mapping
from dataclasses import dataclass
from enum import StrEnum
from typing import Any, Final

from ...proof.formal_verification_contracts import content_identity
from ...proof.mcp_contract_obligations import McpGraphContractObligation, McpObligationDisposition
from ..capabilities import (
    CapabilityEvidenceReceipt,
    CapabilityReceipt,
    CapabilityStatus,
    NetworkMode,
)
from .registry import OperatorRegistry
from .registry_repairs import ast_span_identity

DISPATCH_REPAIR_PREVIEW_INTERFACE: Final[str] = "DispatchRepairPreview@1"
DISPATCH_REPAIR_PREVIEW_SCHEMA: Final[str] = (
    "ipfs_accelerate_py/agent-supervisor/dispatch-repair-preview@1"
)
_ACTIVATION_STATUS: Final[str] = "integration_pending_dcr035_dcr040_dcr070_dcr072"
_ACTIONS: Final[frozenset[str]] = frozenset(
    {"register_static_dispatch", "expose_cec_prove_dispatch"}
)
_FORBIDDEN_ROUTE_PARTS: Final[frozenset[str]] = frozenset(
    {"llm", "model", "provider", "fallback", "rescue", "retry", "remote"}
)


class DispatchPreviewStatus(StrEnum):
    PREVIEWED = "previewed"
    ABSTAINED = "abstained"
    REJECTED = "rejected"


class DispatchRepairPreviewError(ValueError):
    """The closed, non-executing dispatch preview request is invalid."""


def _digest(value: bytes) -> str:
    return "sha256:" + hashlib.sha256(value).hexdigest()


def _text(value: Any, field: str) -> str:
    if (
        not isinstance(value, str)
        or not value
        or any(character in value for character in "\n\r;|&`$<>")
    ):
        raise DispatchRepairPreviewError(f"{field} must be closed text")
    return value


def _dotted_name(node: ast.AST) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        prefix = _dotted_name(node.value)
        return f"{prefix}.{node.attr}" if prefix else ""
    return ""


def _is_forbidden_route(value: str) -> bool:
    return bool(set(value.lower().split(".")) & _FORBIDDEN_ROUTE_PARTS)


def _request_cid(request: Mapping[str, Any]) -> str:
    def canonical(value: Any) -> Any:
        if isinstance(value, bytes):
            return base64.b64encode(value).decode("ascii")
        if isinstance(
            value, (CapabilityReceipt, CapabilityEvidenceReceipt, McpGraphContractObligation)
        ):
            return {"type": type(value).__name__, "value": value.to_dict()}
        if isinstance(value, tuple):
            return [canonical(item) for item in value]
        if isinstance(value, Mapping):
            return {str(key): canonical(item) for key, item in value.items()}
        return value

    return content_identity({key: canonical(value) for key, value in request.items()})


def _abstain(reason: str, request_cid: str) -> DispatchRepairPreview:
    return DispatchRepairPreview(
        status=DispatchPreviewStatus.ABSTAINED, reason=reason, request_cid=request_cid
    )


@dataclass(frozen=True)
class DispatchRepairPreview:
    status: DispatchPreviewStatus
    reason: str
    request_cid: str = ""
    operator_id: str = ""
    manifest_cid: str = ""
    old_digest: str = ""
    new_digest: str = ""
    forward_diff: str = ""
    inverse_diff: str = ""
    after_bytes: bytes = b""
    capability_receipt_id: str = ""
    capability_evidence_receipt_ids: tuple[str, ...] = ()
    obligation_id: str = ""
    obligation_cid: str = ""
    equivalence_predicates: tuple[Mapping[str, str], ...] = ()

    def to_dict(self) -> dict[str, Any]:
        predicates = [dict(item) for item in self.equivalence_predicates]
        return {
            "schema": DISPATCH_REPAIR_PREVIEW_SCHEMA,
            "interface": DISPATCH_REPAIR_PREVIEW_INTERFACE,
            "authoritative": False,
            "execution_authorized": False,
            "activation_status": _ACTIVATION_STATUS,
            "status": self.status.value,
            "reason": self.reason,
            "request_cid": self.request_cid,
            "operator_id": self.operator_id,
            "manifest_cid": self.manifest_cid,
            "old_digest": self.old_digest,
            "new_digest": self.new_digest,
            "forward_diff": self.forward_diff,
            "inverse_diff": self.inverse_diff,
            "after_base64": base64.b64encode(self.after_bytes).decode("ascii"),
            "capability_receipt_id": self.capability_receipt_id,
            "capability_evidence_receipt_ids": list(self.capability_evidence_receipt_ids),
            "obligation_id": self.obligation_id,
            "obligation_cid": self.obligation_cid,
            "equivalence_predicates": predicates,
            "equivalence_predicates_cid": content_identity(predicates),
            "model_call_count": 0,
        }


def _require_exact_keys(value: Any, keys: set[str], field: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping) or set(value) != keys:
        raise DispatchRepairPreviewError(f"{field} fields are closed")
    return value


def _capability(
    capability: Any, evidence: Any, *, handler_module: str, handler_symbol: str
) -> tuple[str, tuple[str, ...]]:
    if not isinstance(capability, CapabilityReceipt):
        raise DispatchRepairPreviewError("typed DCR-004 capability receipt is required")
    if (
        capability.capability_id != "ipfs_datasets_py.logic"
        or capability.status is not CapabilityStatus.AVAILABLE
        or not capability.available
        or not capability.origin.endswith("logic_tools.py")
        or handler_module != "ipfs_datasets_py.logic_tools"
        or handler_symbol != "cec_prove"
        or "cec_prove" not in capability.symbols
        or capability.missing_symbols
        or not capability.expected_version
        or capability.distribution_version != capability.expected_version
        or not capability.content_digest.startswith("module:sha256:")
        or not capability.initialized
        or not capability.reconstructed
        or not capability.self_test_passed
        or capability.network_mode is not NetworkMode.OFFLINE
        or capability.reason_codes
    ):
        raise DispatchRepairPreviewError("current ipfs_datasets_py.logic capability is required")
    if not isinstance(evidence, tuple) or len(evidence) != 3:
        raise DispatchRepairPreviewError("exact typed DCR-004 evidence receipt set is required")
    if any(not isinstance(item, CapabilityEvidenceReceipt) for item in evidence):
        raise DispatchRepairPreviewError("capability evidence must use typed DCR-004 receipts")
    if {item.evidence_kind for item in evidence} != {
        "initialization",
        "reconstruction",
        "self_test",
    }:
        raise DispatchRepairPreviewError("capability evidence kinds are incomplete or ambiguous")
    if not all(
        item.verifies(
            evidence_id=capability.capability_id,
            evidence_kind=item.evidence_kind,
            subject_id=capability.capability_id,
            subject_digest=capability.content_digest,
            subject_version=capability.expected_version,
        )
        and item.receipt_id.startswith("capability-evidence:sha256:")
        for item in evidence
    ):
        raise DispatchRepairPreviewError("capability evidence is stale, forged, or non-offline")
    return capability.receipt_id, tuple(sorted(item.receipt_id for item in evidence))


def _handler(value: Any) -> tuple[str, str, str]:
    semantic = _require_exact_keys(
        value, {"handler_id", "module", "symbol", "semantic_cid", "existing"}, "handler_semantic"
    )
    if semantic["existing"] is not True:
        raise DispatchRepairPreviewError(
            "handler semantic identity must describe an existing handler"
        )
    module = _text(semantic["module"], "handler module")
    symbol = _text(semantic["symbol"], "handler symbol")
    if _is_forbidden_route(module) or _is_forbidden_route(symbol):
        raise DispatchRepairPreviewError("model/provider handler routes are forbidden")
    _text(semantic["handler_id"], "handler_id")
    return module, symbol, _text(semantic["semantic_cid"], "handler semantic_cid")


def _obligation(value: Any, semantic_target: str) -> tuple[str, str]:
    if not isinstance(value, McpGraphContractObligation):
        raise DispatchRepairPreviewError("typed DCR-031 MCP graph obligation is required")
    if (
        value.disposition is not McpObligationDisposition.OPEN
        or not value.graph_cid
        or not value.candidate_cid
        or not value.input_cids
        or value.effect_semantics != semantic_target
        or set((value.graph_cid, value.candidate_cid, *value.input_cids)) - set(value.cid_bindings)
        or not value.schema_bindings
    ):
        raise DispatchRepairPreviewError("DCR-031 obligation target is stale or drifted")
    return value.obligation_id, content_identity(value.to_dict())


def _is_imported_handler(tree: ast.AST, module: str, symbol: str) -> bool:
    return any(
        isinstance(node, ast.ImportFrom)
        and node.module == module
        and any(
            alias.name == symbol and (alias.asname is None or alias.asname == symbol)
            for alias in node.names
        )
        for node in tree.body
    )


def _has_synthesized_handler(tree: ast.AST, symbol: str) -> bool:
    return any(
        isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        and node.name == symbol
        for node in tree.body
    )


def _registration_calls(tree: ast.AST, api: str) -> list[ast.Call]:
    return [
        node
        for node in ast.walk(tree)
        if isinstance(node, ast.Call) and _dotted_name(node.func) == api
    ]


def _static_call(call: ast.Call) -> tuple[str, str] | None:
    if (
        len(call.args) != 2
        or call.keywords
        or not isinstance(call.args[0], ast.Constant)
        or not isinstance(call.args[0].value, str)
        or not isinstance(call.args[1], ast.Name)
    ):
        return None
    return call.args[0].value, call.args[1].id


def _make_preview(
    source: bytes,
    addition: bytes,
    *,
    request_cid: str,
    operator_id: str,
    manifest_cid: str,
    receipt_id: str,
    evidence_ids: tuple[str, ...],
    obligation_id: str,
    obligation_cid: str,
    predicates: tuple[Mapping[str, str], ...],
) -> DispatchRepairPreview:
    after = source + addition
    before_lines = source.decode("utf-8").splitlines(keepends=True)
    after_lines = after.decode("utf-8").splitlines(keepends=True)
    forward = "".join(difflib.unified_diff(before_lines, after_lines, "before", "after"))
    inverse = "".join(difflib.unified_diff(after_lines, before_lines, "after", "before"))
    if not addition or after == source or not forward or not inverse:
        return _abstain("nonempty_forward_and_inverse_required", request_cid)
    return DispatchRepairPreview(
        status=DispatchPreviewStatus.PREVIEWED,
        reason="validation_pending",
        request_cid=request_cid,
        operator_id=operator_id,
        manifest_cid=manifest_cid,
        old_digest=_digest(source),
        new_digest=_digest(after),
        forward_diff=forward,
        inverse_diff=inverse,
        after_bytes=after,
        capability_receipt_id=receipt_id,
        capability_evidence_receipt_ids=evidence_ids,
        obligation_id=obligation_id,
        obligation_cid=obligation_cid,
        equivalence_predicates=predicates,
    )


def build_dispatch_repair_preview(
    request: Mapping[str, Any], *, registry: OperatorRegistry, manifest_cid: str
) -> DispatchRepairPreview:
    """Build a reviewed static dispatch preview without executing or writing anything."""
    try:
        fields = {
            "operator_id",
            "action",
            "owner_root",
            "relative_path",
            "source_bytes",
            "source_digest",
            "anchor",
            "payload",
            "handler_semantic",
            "capability_receipt",
            "capability_evidence_receipts",
            "obligation",
        }
        request = _require_exact_keys(request, fields, "request")
        source = request["source_bytes"]
        if not isinstance(source, bytes) or not source:
            raise DispatchRepairPreviewError("exact current source bytes are required")
        if _text(request["source_digest"], "source_digest") != _digest(source):
            raise DispatchRepairPreviewError("source digest is stale")
        request_cid = _request_cid(request)
        action = _text(request["action"], "action")
        if action not in _ACTIONS:
            raise DispatchRepairPreviewError("dispatch action is not reviewed")
        operator_id = _text(request["operator_id"], "operator_id")
        owner = _text(request["owner_root"], "owner_root")
        path = _text(request["relative_path"], "relative_path")
        report = registry.report()
        if manifest_cid != report["registry_cid"]:
            raise DispatchRepairPreviewError("reviewed operator manifest CID is stale")
        descriptor = {item.operator_id: item for item in registry.enumerate()}.get(operator_id)
        if descriptor is None:
            raise DispatchRepairPreviewError("operator is absent from reviewed manifest")
        if owner != descriptor.owner_root or path not in descriptor.write_scope:
            raise DispatchRepairPreviewError("owner root or write scope is not admitted")
        payload = _require_exact_keys(
            request["payload"],
            {"operation", "dispatcher_api", "handler_symbol", "semantic_target"},
            "payload",
        )
        operation = _text(payload["operation"], "operation")
        api = _text(payload["dispatcher_api"], "dispatcher_api")
        symbol = _text(payload["handler_symbol"], "handler_symbol")
        target = _text(payload["semantic_target"], "semantic_target")
        if _is_forbidden_route(api) or _is_forbidden_route(operation):
            raise DispatchRepairPreviewError("model/provider dispatch routes are forbidden")
        module, handler_symbol, semantic_cid = _handler(request["handler_semantic"])
        if handler_symbol != symbol:
            raise DispatchRepairPreviewError("handler semantic identity does not match payload")
        receipt_id, evidence_ids = _capability(
            request["capability_receipt"],
            request["capability_evidence_receipts"],
            handler_module=module,
            handler_symbol=symbol,
        )
        obligation_id, obligation_cid = _obligation(request["obligation"], target)
        if action == "expose_cec_prove_dispatch" and symbol != "cec_prove":
            raise DispatchRepairPreviewError(
                "cec_prove dispatch must expose existing logic_tools semantics"
            )
        try:
            tree = ast.parse(source, filename=path)
        except SyntaxError:
            return _abstain("source_ast_unavailable", request_cid)
        if _has_synthesized_handler(tree, symbol) or not _is_imported_handler(tree, module, symbol):
            return _abstain("existing_handler_semantics_not_statically_resolved", request_cid)
        calls = _registration_calls(tree, api)
        if len(calls) != 1:
            return _abstain("dispatcher_api_not_uniquely_resolved", request_cid)
        if _static_call(calls[0]) is None:
            return _abstain("dynamic_dispatch_registration", request_cid)
        if not isinstance(request["anchor"], Mapping) or dict(
            request["anchor"]
        ) != ast_span_identity(source, calls[0]):
            raise DispatchRepairPreviewError(
                "anchor is stale or does not identify dispatcher registration"
            )
        if operation == _static_call(calls[0])[0]:
            return _abstain("dispatch_registration_already_present", request_cid)
        addition = (b"" if source.endswith(b"\n") else b"\n") + (
            f"{api}({operation!r}, {symbol})\n".encode()
        )
        predicates: tuple[Mapping[str, str], ...] = (
            {
                "kind": "local_mcp_semantic_equivalence",
                "semantic_target": target,
                "local_handler_semantic_cid": semantic_cid,
                "mcp_operation": operation,
                "transport": "loopback_mcp",
            },
            {
                "kind": "capability_bound_existing_handler",
                "capability_receipt_id": receipt_id,
                "module": module,
                "symbol": symbol,
            },
        )
        return _make_preview(
            source,
            addition,
            request_cid=request_cid,
            operator_id=operator_id,
            manifest_cid=manifest_cid,
            receipt_id=receipt_id,
            evidence_ids=evidence_ids,
            obligation_id=obligation_id,
            obligation_cid=obligation_cid,
            predicates=predicates,
        )
    except DispatchRepairPreviewError as exc:
        return DispatchRepairPreview(status=DispatchPreviewStatus.REJECTED, reason=str(exc))


